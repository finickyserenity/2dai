// Copies the wire-protocol schemas from the server repo into the client so both
// sides share one definition. Run after any change under server/src/protocol.
//   npm run sync:protocol            (expects ../server or ./server next to this repo)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const candidates = [process.env.SERVER_DIR, path.join(root, 'server'), path.join(root, '..', 'server')].filter(Boolean)
const source = candidates.map((dir) => path.join(dir, 'src', 'protocol')).find((dir) => fs.existsSync(dir))
if (!source) {
  console.error('Could not find the server repo (looked for server/src/protocol). Set SERVER_DIR.')
  process.exit(1)
}
const target = path.join(root, 'src', 'sync', 'protocol')
fs.rmSync(target, { recursive: true, force: true })
fs.mkdirSync(target, { recursive: true })
const banner = '// Generated by scripts/sync-protocol.mjs from the 2dai-server repo. Do not edit here.\n'
for (const name of fs.readdirSync(source).filter((file) => file.endsWith('.ts')).sort()) {
  fs.writeFileSync(path.join(target, name), banner + fs.readFileSync(path.join(source, name), 'utf8'))
  console.log(`copied ${name}`)
}
